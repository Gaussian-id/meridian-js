import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const targets = [
  { spec: "spec/meridian-public.json", out: "packages/meridian/src/generated/public.ts" },
  { spec: "spec/meridian-admin.json", out: "packages/meridian/src/generated/admin.ts" },
];

const header = "// Generated by scripts/generate-types.mjs from spec/. Never edit by hand.\n\n";
const check = process.argv.includes("--check");

// [1] Generate each document's types in memory.
const generated = await Promise.all(
  targets.map(async ({ spec, out }) => {
    const ast = await openapiTS(pathToFileURL(spec));

    return { out, text: header + astToString(ast) };
  }),
);

// [2] In check mode compare with the committed files; otherwise write them.
if (check) {
  const stale = generated
    .filter(({ out, text }) => readFileSync(out, "utf8") !== text)
    .map(({ out }) => out);

  if (stale.length > 0) {
    console.error(`Generated types drift from spec/: ${stale.join(", ")}. Run pnpm generate.`);
    process.exit(1);
  }

  console.log("Generated types match spec/.");
} else {
  for (const { out, text } of generated) writeFileSync(out, text);
  console.log(`Wrote ${generated.length} generated files.`);
}
